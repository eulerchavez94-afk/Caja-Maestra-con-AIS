            suppliers = suppliers,
            employees = employees,
            cashShifts = cashShifts,
            cashShiftMovements = cashShiftMovements,
            businessSettings = settings,
            securityVault = vault,
            isLegacyV1 = false,
            folioSequences = folioSequences,
            inventoryMovements = inventoryMovements
        )
    }

