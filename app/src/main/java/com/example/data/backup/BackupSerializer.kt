/**
 * Versioned encrypted backup serializer/deserializer for Caja Maestra.
 *
 * Format v2 ("CAJA_MAESTRA_BACKUP"):
 * - Outer JSON envelope with unencrypted structural metadata bound via AES-256-GCM AAD.
 * - Inner payload compressed with GZIP, encrypted with PBKDF2WithHmacSHA256 (120,000 iterations)
 *   + AES-256-GCM, and double-checked with an inner SHA-256 integrity digest.
 * - Supports reading/migrating legacy v1 Base64 backups generated by prior app builds.
 */
object BackupSerializer {
    const val MAGIC_V2 = "CAJA_MAESTRA_BACKUP"
    const val CURRENT_FORMAT_VERSION = 2
    const val ROOM_SCHEMA_VERSION = 5
    private const val EXPECTED_KDF = "PBKDF2WithHmacSHA256"
    private const val EXPECTED_CIPHER = "AES/GCM/NoPadding"

    private fun buildAad(
        magic: String,
        formatVersion: Int,
        roomSchemaVersion: Int,
        createdAt: Long
    ): ByteArray {
        return "$magic|v$formatVersion|room$roomSchemaVersion|$createdAt".toByteArray(Charsets.UTF_8)
    }

    fun inspectBytes(bytes: ByteArray, fileName: String = ""): BackupInspectionResult {
        val displayName = fileName.ifBlank { "Respaldo seleccionado" }
        if (bytes.isEmpty()) {
            return BackupInspectionResult(
                fileName = displayName,
                sizeBytes = 0L,
                formatType = BackupFormatType.EMPTY,
                formatVersion = 0,
                roomSchemaVersion = 0,
                createdAt = 0L,
                kdf = "",
                cipher = "",
                includesSecurityVault = false,
                isValidForRestore = false,
                statusMessage = "El archivo está vacío (0 bytes)."
            )
        }

        val rawText = try {
            String(bytes, Charsets.UTF_8).trim()
        } catch (_: Exception) {
            return invalidInspection(displayName, bytes.size.toLong(), "No se pudo leer el contenido UTF-8 del archivo.")
        }

        if (rawText.isEmpty()) {
            return BackupInspectionResult(
                fileName = displayName,
                sizeBytes = bytes.size.toLong(),
                formatType = BackupFormatType.EMPTY,
                formatVersion = 0,
                roomSchemaVersion = 0,
                createdAt = 0L,
                kdf = "",
                cipher = "",
                includesSecurityVault = false,
                isValidForRestore = false,
                statusMessage = "El archivo no contiene datos."
            )
        }

        if (rawText.startsWith("{")) {
            return try {
                val env = JSONObject(rawText)
                val magic = env.optString("magic", "")
                if (magic != MAGIC_V2) {
                    return invalidInspection(
                        displayName,
                        bytes.size.toLong(),
                        "El archivo JSON no tiene la firma de Caja Maestra."
                    )
                }
                val version = env.optInt("formatVersion", -1)
                if (version < 1 || version > CURRENT_FORMAT_VERSION) {
                    return BackupInspectionResult(
                        fileName = displayName,
                        sizeBytes = bytes.size.toLong(),
                        formatType = BackupFormatType.UNSUPPORTED_VERSION,
                        formatVersion = version,
                        roomSchemaVersion = env.optInt("roomSchemaVersion", 0),
                        createdAt = env.optLong("createdAt", 0L),
                        kdf = env.optString("kdf", ""),
                        cipher = env.optString("cipher", ""),
                        includesSecurityVault = env.optBoolean("includesSecurityVault", false),
                        isValidForRestore = false,
                        statusMessage = "Versión de formato incompatible (v$version). Versión soportada: hasta v$CURRENT_FORMAT_VERSION."
                    )
                }
                val roomVer = env.optInt("roomSchemaVersion", 0)
                if (roomVer < 1 || roomVer > ROOM_SCHEMA_VERSION) {
                    return BackupInspectionResult(
                        fileName = displayName,
                        sizeBytes = bytes.size.toLong(),
                        formatType = BackupFormatType.UNSUPPORTED_VERSION,
                        formatVersion = version,
                        roomSchemaVersion = roomVer,
                        createdAt = env.optLong("createdAt", 0L),
                        kdf = env.optString("kdf", ""),
                        cipher = env.optString("cipher", ""),
                        includesSecurityVault = env.optBoolean("includesSecurityVault", false),
                        isValidForRestore = false,
                        statusMessage = "Esquema de base de datos incompatible (Room v$roomVer)."
                    )
                }
                val payload = env.optString("payload", "")
                val kdf = env.optString("kdf", "")
                val cipher = env.optString("cipher", "")
                val kdfIterations = env.optInt("kdfIterations", 0)
                if (payload.isBlank() || kdf != EXPECTED_KDF || cipher != EXPECTED_CIPHER || kdfIterations < 10_000) {
                    return invalidInspection(
                        displayName,
                        bytes.size.toLong(),
                        "Cabecera criptográfica incompleta o alterada."
                    )
                }

                BackupInspectionResult(
                    fileName = displayName,
                    sizeBytes = bytes.size.toLong(),
                    formatType = BackupFormatType.V2_ENVELOPE,
                    formatVersion = version,
                    roomSchemaVersion = roomVer,
                    createdAt = env.optLong("createdAt", 0L),
                    kdf = kdf,
                    cipher = cipher,
                    includesSecurityVault = env.optBoolean("includesSecurityVault", false),
                    isValidForRestore = true,
                    statusMessage = "Archivo válido: Caja Maestra v$version (Room v$roomVer, $cipher)."
                )
            } catch (_: Exception) {
                invalidInspection(
                    displayName,
                    bytes.size.toLong(),
                    "Estructura del archivo dañada o truncada."
                )
            }
        }

        // Legacy v1 detection: raw Base64(salt[16] + iv[12] + gcmCiphertext[>=16])
        val decoded = try {
            Base64.decode(rawText, Base64.NO_WRAP)
        } catch (_: Exception) {
            null
        }
        if (decoded != null && decoded.size >= 44) {
            return BackupInspectionResult(
                fileName = displayName,
                sizeBytes = bytes.size.toLong(),
                formatType = BackupFormatType.LEGACY_V1,
                formatVersion = 1,
                roomSchemaVersion = 2,
                createdAt = 0L,
                kdf = EXPECTED_KDF,
                cipher = EXPECTED_CIPHER,
                includesSecurityVault = false,
                isValidForRestore = true,
                statusMessage = "Formato heredado v1 detectado (Base64 AES-256-GCM; restaura Inventario y Ventas)."
            )
        }

        return invalidInspection(
            displayName,
            bytes.size.toLong(),
            "Formato desconocido o archivo dañado."
        )
    }

    private fun invalidInspection(
        fileName: String,
        sizeBytes: Long,
        message: String
    ): BackupInspectionResult {
        return BackupInspectionResult(
            fileName = fileName,
            sizeBytes = sizeBytes,
            formatType = BackupFormatType.INVALID_FORMAT,
            formatVersion = 0,
            roomSchemaVersion = 0,
            createdAt = 0L,
            kdf = "",
            cipher = "",
            includesSecurityVault = false,
            isValidForRestore = false,
            statusMessage = message
        )
    }

    fun serializeEncryptedV2(dataset: BackupDataset, passphrase: String): ByteArray {
        val dataJson = serializeDataObject(dataset).toString()
        val digest = AesEncryptionUtil.sha256Hex(dataJson.toByteArray(Charsets.UTF_8))

        val payloadRoot = JSONObject().apply {
            put("formatVersion", CURRENT_FORMAT_VERSION)
            put("roomSchemaVersion", ROOM_SCHEMA_VERSION)
            put("createdAt", dataset.createdAt)
            put("counts", serializeCounts(dataset.toCounts()))
            put("dataJson", dataJson)
            put("integritySha256", digest)
        }

        val aad = buildAad(MAGIC_V2, CURRENT_FORMAT_VERSION, ROOM_SCHEMA_VERSION, dataset.createdAt)
        val encryptedPayload = AesEncryptionUtil.encryptPayloadWithGzipAndAad(
            plainBytes = payloadRoot.toString().toByteArray(Charsets.UTF_8),
            passphrase = passphrase,
            iterations = AesEncryptionUtil.BACKUP_KDF_ITERATIONS,
            aad = aad
        )

        val envelope = JSONObject().apply {
            put("magic", MAGIC_V2)
            put("formatVersion", CURRENT_FORMAT_VERSION)
            put("roomSchemaVersion", ROOM_SCHEMA_VERSION)
            put("createdAt", dataset.createdAt)
            put("compression", "GZIP")
            put("kdf", EXPECTED_KDF)
            put("kdfIterations", AesEncryptionUtil.BACKUP_KDF_ITERATIONS)
            put("cipher", EXPECTED_CIPHER)
            put("includesSecurityVault", dataset.securityVault != null)
            put("payload", encryptedPayload)
        }
        return envelope.toString().toByteArray(Charsets.UTF_8)
    }

    fun decryptAndParse(bytes: ByteArray, passphrase: String): Result<BackupDataset> {
        val inspection = inspectBytes(bytes)
        if (!inspection.isValidForRestore) {
            return Result.failure(IllegalArgumentException(inspection.statusMessage))
        }

        val rawText = String(bytes, Charsets.UTF_8).trim()
        return when (inspection.formatType) {
            BackupFormatType.V2_ENVELOPE -> decryptV2(rawText, passphrase)
            BackupFormatType.LEGACY_V1 -> decryptLegacyV1(rawText, passphrase)
            else -> Result.failure(IllegalArgumentException(inspection.statusMessage))
        }
    }

    private fun decryptV2(envelopeText: String, passphrase: String): Result<BackupDataset> {
        return try {
            val env = JSONObject(envelopeText)
            val magic = env.getString("magic")
            val formatVersion = env.getInt("formatVersion")
            val roomSchemaVersion = env.getInt("roomSchemaVersion")
            val createdAt = env.getLong("createdAt")
            val iterations = env.getInt("kdfIterations")
            val payloadBase64 = env.getString("payload")

            val aad = buildAad(magic, formatVersion, roomSchemaVersion, createdAt)
            val plainBytes = AesEncryptionUtil.decryptPayloadWithGzipAndAad(
                payloadBase64 = payloadBase64,
                passphrase = passphrase,
                iterations = iterations,
                aad = aad
            ).getOrElse {
                return Result.failure(
                    IllegalArgumentException("Contraseña incorrecta o archivo de respaldo dañado/alterado.")
                )
            }

            val payloadRoot = JSONObject(String(plainBytes, Charsets.UTF_8))
            if (payloadRoot.optInt("formatVersion", -1) != formatVersion) {
                return Result.failure(IllegalArgumentException("Inconsistencia de versión dentro del respaldo."))
            }

            val dataJson = payloadRoot.getString("dataJson")
            val expectedSha = payloadRoot.getString("integritySha256")
            val actualSha = AesEncryptionUtil.sha256Hex(dataJson.toByteArray(Charsets.UTF_8))
            if (!expectedSha.equals(actualSha, ignoreCase = true)) {
                return Result.failure(IllegalArgumentException("Falló la verificación de integridad SHA-256."))
            }

            val dataObj = JSONObject(dataJson)
            val dataset = parseDataObject(
                dataObj = dataObj,
                formatVersion = formatVersion,
                roomSchemaVersion = roomSchemaVersion,
                createdAt = createdAt
            )

            // Verify outer counts match parsed entity lists
            val expectedCounts = payloadRoot.getJSONObject("counts")
            val actualCounts = dataset.toCounts()
            if (expectedCounts.getInt("inventory") != actualCounts.inventory ||
                expectedCounts.getInt("sales") != actualCounts.sales ||
                expectedCounts.getInt("purchases") != actualCounts.purchases ||
                expectedCounts.getInt("extraMovements") != actualCounts.extraMovements ||
                expectedCounts.getInt("rentalsLoans") != actualCounts.rentalsLoans ||
                expectedCounts.getInt("clients") != actualCounts.clients ||
                expectedCounts.getInt("suppliers") != actualCounts.suppliers ||
                expectedCounts.getInt("employees") != actualCounts.employees ||
                expectedCounts.getInt("cashShifts") != actualCounts.cashShifts ||
                expectedCounts.getInt("cashShiftMovements") != actualCounts.cashShiftMovements ||
                expectedCounts.optInt("inventoryMovements", 0) != actualCounts.inventoryMovements
            ) {
                return Result.failure(IllegalArgumentException("El conteo interno de registros no coincide con los datos."))
            }

            Result.success(dataset)
        } catch (e: Exception) {
            Result.failure(IllegalArgumentException(e.message ?: "Error al procesar el respaldo v2.", e))
        }
    }

    private fun decryptLegacyV1(base64Text: String, passphrase: String): Result<BackupDataset> {
        val plainText = AesEncryptionUtil.decrypt(base64Text, passphrase).getOrElse {
            return Result.failure(IllegalArgumentException("Contraseña incorrecta o respaldo v1 corrupto."))
        }
        return try {
            val root = JSONObject(plainText)
            val version = root.optInt("version", -1)
            if (version != 1) {
                return Result.failure(IllegalArgumentException("Versión heredada no soportada: $version"))
            }
            val timestamp = root.optLong("timestamp", System.currentTimeMillis())
            val businessName = root.optString("business", "")
                .ifBlank { root.optString("businessName", "") }
                .takeIf { it.isNotBlank() }

            val invArr = root.optJSONArray("inventory") ?: JSONArray()
            val inventory = buildList {
                for (i in 0 until invArr.length()) {
                    val o = invArr.getJSONObject(i)
                    add(
                        InventoryItem(
                            id = o.optLong("id", 0L),
                            name = o.getString("name"),
                            code = o.optString("code", ""),
                            costPrice = o.optDouble("cost", 0.0),
                            salePrice = o.optDouble("sale", 0.0),
                            stock = o.optDouble("stock", 0.0),
                            minStock = o.optDouble("minStock", 5.0),
                            category = o.optString("category", "General"),
                            unit = o.optString("unit", "Pza"),
                            type = ItemType.valueOf(o.optString("type", ItemType.PRODUCTO.name)),
                            isWaste = o.optBoolean("isWaste", false),
                            notes = o.optString("notes", "")
                        )
                    )
                }
            }

            val salesArr = root.optJSONArray("sales") ?: JSONArray()
            val sales = buildList {
                for (i in 0 until salesArr.length()) {
                    val o = salesArr.getJSONObject(i)
                    val total = o.getDouble("total")
                    add(
                        Sale(
                            id = o.optLong("id", (i + 1).toLong()),
                            folio = o.getString("folio"),
                            type = SaleType.VENTA,
                            status = SaleStatus.valueOf(o.optString("status", SaleStatus.PAGADA.name)),
                            customerId = null,
                            customerName = o.optString("customer", "Público General"),
                            subtotal = o.optDouble("subtotal", total),
                            discount = o.optDouble("discount", 0.0),
                            total = total,
                            paidAmount = o.optDouble("paidAmount", total),
                            changeAmount = o.optDouble("changeAmount", 0.0),
                            paymentMethod = o.optString("paymentMethod", "Efectivo"),
                            date = o.optLong("date", timestamp),
                            sellerName = o.optString("sellerName", "Respaldo v1"),
                            notes = o.optString("notes", ""),
                            itemsJson = o.optString("itemsJson", ""),
                            shiftId = null
                        )
                    )
                }
            }

            Result.success(
                BackupDataset(
                    formatVersion = 1,
                    roomSchemaVersion = 2,
                    createdAt = timestamp,
                    inventory = inventory,
                    sales = sales,
                    purchases = emptyList(),
                    extraMovements = emptyList(),
                    rentalsLoans = emptyList(),
                    clients = emptyList(),
                    suppliers = emptyList(),
                    employees = emptyList(),
                    cashShifts = emptyList(),
                    cashShiftMovements = emptyList(),
                    businessSettings = null,
                    securityVault = null,
                    isLegacyV1 = true,
                    legacyBusinessName = businessName
                )
            )
        } catch (e: Exception) {
            Result.failure(IllegalArgumentException("Estructura heredada v1 inválida: ${e.message}", e))
        }
    }

    /**
     * Used internally for KeyStore-encrypted preventive rollback snapshots.
     */
    fun serializeSnapshotJson(dataset: BackupDataset): ByteArray {
        val root = JSONObject().apply {
            put("formatVersion", dataset.formatVersion)
            put("roomSchemaVersion", dataset.roomSchemaVersion)
            put("createdAt", dataset.createdAt)
            put("data", serializeDataObject(dataset))
        }
        return root.toString().toByteArray(Charsets.UTF_8)
    }

    fun parseSnapshotJson(bytes: ByteArray): BackupDataset {
        val root = JSONObject(String(bytes, Charsets.UTF_8))
        return parseDataObject(
            dataObj = root.getJSONObject("data"),
            formatVersion = root.getInt("formatVersion"),
            roomSchemaVersion = root.getInt("roomSchemaVersion"),
            createdAt = root.getLong("createdAt")
        )
    }

    private fun serializeCounts(counts: BackupCounts): JSONObject {
        return JSONObject().apply {
            put("inventory", counts.inventory)
            put("sales", counts.sales)
            put("purchases", counts.purchases)
            put("extraMovements", counts.extraMovements)
            put("rentalsLoans", counts.rentalsLoans)
            put("clients", counts.clients)
            put("suppliers", counts.suppliers)
            put("employees", counts.employees)
            put("cashShifts", counts.cashShifts)
            put("cashShiftMovements", counts.cashShiftMovements)
            put("inventoryMovements", counts.inventoryMovements)
        }
    }

    fun serializeDataObject(dataset: BackupDataset): JSONObject {
        return JSONObject().apply {
            put("inventory", JSONArray().apply {
                dataset.inventory.forEach { item ->
                    put(JSONObject().apply {
                        put("id", item.id)
                        put("name", item.name)
                        put("code", item.code)
                        put("costPrice", item.costPrice)
                        put("salePrice", item.salePrice)
                        put("stock", item.stock)
                        put("minStock", item.minStock)
                        put("category", item.category)
                        put("unit", item.unit)
                        put("type", item.type.name)
                        put("isWaste", item.isWaste)
                        put("isRawMaterial", item.isRawMaterial)
                        put("notes", item.notes)
                    })
                }
            })

            put("sales", JSONArray().apply {
                dataset.sales.forEach { sale ->
                    put(JSONObject().apply {
                        put("id", sale.id)
                        put("folio", sale.folio)
                        put("type", sale.type.name)
                        put("status", sale.status.name)
                        putNullableLong("customerId", sale.customerId)
                        put("customerName", sale.customerName)
                        put("subtotal", sale.subtotal)
                        put("discount", sale.discount)
                        put("total", sale.total)
                        put("paidAmount", sale.paidAmount)
                        put("changeAmount", sale.changeAmount)
                        put("paymentMethod", sale.paymentMethod)
                        put("date", sale.date)
                        put("sellerName", sale.sellerName)
                        put("notes", sale.notes)
                        put("itemsJson", sale.itemsJson)
                        putNullableLong("shiftId", sale.shiftId)
                    })
                }
            })

            put("purchases", JSONArray().apply {
                dataset.purchases.forEach { p ->
                    put(JSONObject().apply {
                        put("id", p.id)
                        put("folio", p.folio)
                        putNullableLong("supplierId", p.supplierId)
                        put("supplierName", p.supplierName)
                        put("total", p.total)
                        put("date", p.date)
                        put("isCredit", p.isCredit)
                        put("notes", p.notes)
                        put("itemsJson", p.itemsJson)
                    })
                }
            })

            put("extraMovements", JSONArray().apply {
                dataset.extraMovements.forEach { m ->
                    put(JSONObject().apply {
                        put("id", m.id)
                        put("type", m.type.name)
                        put("concept", m.concept)
                        put("category", m.category)
                        put("amount", m.amount)
                        put("isCredit", m.isCredit)
                        put("date", m.date)
                        put("notes", m.notes)
                    })
                }
            })

            put("rentalsLoans", JSONArray().apply {
                dataset.rentalsLoans.forEach { r ->
                    put(JSONObject().apply {
                        put("id", r.id)
                        put("isRental", r.isRental)
                        put("contactName", r.contactName)
                        put("itemOrReason", r.itemOrReason)
                        put("amount", r.amount)
                        put("depositAmount", r.depositAmount)
                        put("startDate", r.startDate)
                        put("dueDate", r.dueDate)
                        put("isReturnedOrPaid", r.isReturnedOrPaid)
                        put("notes", r.notes)
                    })
                }
            })

            put("clients", JSONArray().apply {
                dataset.clients.forEach { c ->
                    put(JSONObject().apply {
                        put("id", c.id)
                        put("name", c.name)
                        put("company", c.company)
                        put("phone", c.phone)
                        put("email", c.email)
                        put("address", c.address)
                        put("creditBalance", c.creditBalance)
                        put("notes", c.notes)
                    })
                }
            })

            put("suppliers", JSONArray().apply {
                dataset.suppliers.forEach { s ->
                    put(JSONObject().apply {
                        put("id", s.id)
                        put("name", s.name)
                        put("company", s.company)
                        put("contactName", s.contactName)
                        put("phone", s.phone)
                        put("email", s.email)
                        put("address", s.address)
                        put("suppliedProducts", s.suppliedProducts)
                        put("paymentTerms", s.paymentTerms)
                        put("notes", s.notes)
                    })
                }
            })

            put("employees", JSONArray().apply {
                dataset.employees.forEach { e ->
                    put(JSONObject().apply {
                        put("id", e.id)
                        put("name", e.name)
                        put("position", e.position)
                        put("salary", e.salary)
                        put("phone", e.phone)
                        put("email", e.email)
                        put("address", e.address)
                        put("role", e.role.name)
                        // Never export plaintext PINs
                        val safePin = if (e.pin.isNotBlank() && !PasswordHasher.isHashed(e.pin)) {
                            if (PasswordHasher.isLegacyDefaultCredential(e.pin)) "" else PasswordHasher.hash(e.pin)
                        } else {
                            e.pin
                        }
                        put("pin", safePin)
                    })
                }
            })

            put("cashShifts", JSONArray().apply {
                dataset.cashShifts.forEach { cs ->
                    put(JSONObject().apply {
                        put("id", cs.id)
                        put("cashierName", cs.cashierName)
                        put("cashierRole", cs.cashierRole.name)
                        put("openedAt", cs.openedAt)
                        putNullableLong("closedAt", cs.closedAt)
                        put("openingFloat", cs.openingFloat)
                        put("cashSalesTotal", cs.cashSalesTotal)
                        put("cardSalesTotal", cs.cardSalesTotal)
                        put("transferSalesTotal", cs.transferSalesTotal)
                        put("creditSalesTotal", cs.creditSalesTotal)
                        put("cashEntriesTotal", cs.cashEntriesTotal)
                        put("cashWithdrawalsTotal", cs.cashWithdrawalsTotal)
                        put("expectedCash", cs.expectedCash)
                        put("countedCash", cs.countedCash)
                        put("difference", cs.difference)
                        put("nextTurnFloat", cs.nextTurnFloat)
                        put("salesCount", cs.salesCount)
                        put("isOpen", cs.isOpen)
                        put("openingNotes", cs.openingNotes)
                        put("closingNotes", cs.closingNotes)
                    })
                }
            })

            put("cashShiftMovements", JSONArray().apply {
                dataset.cashShiftMovements.forEach { m ->
                    put(JSONObject().apply {
                        put("id", m.id)
                        put("shiftId", m.shiftId)
                        put("type", m.type.name)
                        put("amount", m.amount)
                        put("reason", m.reason)
                        put("performedBy", m.performedBy)
                        put("date", m.date)
                    })
                }
            })

            dataset.businessSettings?.let { put("businessSettings", serializeBusinessSettings(it)) }
            dataset.securityVault?.let { put("securityVault", JSONObject(it.toJson())) }
            if (dataset.folioSequences.isNotEmpty()) {
                put("folioSequences", JSONArray().apply {
                    dataset.folioSequences.forEach { seq ->
                        put(JSONObject().apply {
                            put("sequenceKey", seq.sequenceKey)
                            put("lastNumber", seq.lastNumber)
                        })
                    }
                })
            }
            if (dataset.inventoryMovements.isNotEmpty()) {
                put("inventoryMovements", JSONArray().apply {
                    dataset.inventoryMovements.forEach { mov ->
                        put(JSONObject().apply {
                            put("id", mov.id)
                            put("itemId", mov.itemId)
                            put("itemCode", mov.itemCode)
                            put("itemName", mov.itemName)
                            put("movementType", mov.movementType.name)
                            put("quantityDelta", mov.quantityDelta)
                            put("previousStock", mov.previousStock)
                            put("newStock", mov.newStock)
                            put("referenceFolio", mov.referenceFolio)
                            put("reason", mov.reason)
                            put("performedBy", mov.performedBy)
                            put("date", mov.date)
                        })
                    }
                })
            }
        }
    }

    private fun parseDataObject(
        dataObj: JSONObject,
        formatVersion: Int,
        roomSchemaVersion: Int,
        createdAt: Long
    ): BackupDataset {
